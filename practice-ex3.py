a = int(input("Enter number: "))
b = int(input("Enter number: "))
opere = (input("Enter operator: "))

if ( opere == "+" ):
    print (a+b)
elif ( opere == "-"):
    print (a-b)
elif (opere == "*"):
    print ( a * b)
elif (opere == "/"):
    print ( a / b)
elif (opere == "%"):
    print( a % b)
elif (opere == "**"):
    print( a ** b)


